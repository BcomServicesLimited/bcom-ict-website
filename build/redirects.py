#!/usr/bin/env python3
"""
Generates _redirects for Cloudflare Pages.

Rules come from three places:
  1. the previous site's _redirects, flattened so no rule points at a page that
     no longer exists and no chain is longer than one hop;
  2. consolidation decisions made during the rebuild;
  3. the apex->www rule and the .html-stripping catch-all, which must be last.

Run:  python3 build/redirects.py
"""
import glob
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OLD = pathlib.Path.home() / "BcomITSolutionsPROJECT"

# Pages rebuilt in chunk 7 that the old file redirected away. Carrying these
# across would silently 301 the new suburb pages into the generic support page.
BLOCK = {
    "/it-support-burleigh-heads-gold-coast.html",
    "/it-support-robina-gold-coast.html",
    "/it-support-southport-gold-coast.html",
}

# Old targets that no longer exist -> where they go now. Applied recursively so
# a chain like  /computer-repairs-broadbeach -> /computer-repairs-gold-coast
# -> /on-site-computer-repair-gold-coast  becomes a single hop.
RETARGET = {
    "/computer-repairs-gold-coast":                   "/on-site-computer-repair-gold-coast",
    "/computer-repair-service-gold-coast":            "/on-site-computer-repair-gold-coast",
    "/home-wifi-setup-and-troubleshooting-gold-coast": "/mesh-network-setup-gold-coast",
    "/google-nest-wifi-gold-coast":                   "/mesh-network-setup-gold-coast",
    "/printer-setup-and-support-gold-coast":          "/it-support-and-services-gold-coast",
    "/tech-tips-template.html":                       "/",     # was a self-redirect loop
    "/index":                                         "/",
    "/business":                                      "/services",
}

# Consolidations decided during the rebuild. The consumer WiFi brand pages go to
# business WiFi; the two consumer mesh brands go to mesh setup.
CONSOLIDATE = {
    "/asus-wifi-gold-coast":            "/business-wifi-gold-coast",
    "/d-link-wifi-gold-coast":          "/business-wifi-gold-coast",
    "/linksys-wifi-gold-coast":         "/business-wifi-gold-coast",
    "/netgear-wifi-gold-coast":         "/business-wifi-gold-coast",
    "/tp-link-wifi-gold-coast":         "/business-wifi-gold-coast",
    "/grandstream-wifi-gold-coast":     "/business-wifi-gold-coast",
    "/synology-wifi-gold-coast":        "/business-wifi-gold-coast",
    "/eero-wifi-gold-coast":            "/mesh-network-setup-gold-coast",
    "/google-nest-wifi-gold-coast":     "/mesh-network-setup-gold-coast",
    "/home-wifi-setup-and-troubleshooting-gold-coast": "/mesh-network-setup-gold-coast",
    "/computer-repairs-gold-coast":     "/on-site-computer-repair-gold-coast",
    "/computer-consultant-gold-coast":  "/it-consulting-strategy-gold-coast",
    "/business":                        "/services",
}


def built():
    return {("/" if f == "index.html" else "/" + f[:-5]) for f in glob.glob(str(ROOT / "*.html"))
            for f in [pathlib.Path(f).name]}


def resolve(dst, pages, depth=0):
    """Follow retarget/consolidate hops until we land on a real page."""
    d = dst.rstrip("/") or "/"
    if depth > 6:
        return "/"
    if d in pages:
        return d
    for table in (CONSOLIDATE, RETARGET):
        if d in table:
            return resolve(table[d], pages, depth + 1)
        if d + ".html" in table:
            return resolve(table[d + ".html"], pages, depth + 1)
    return "/"


def main():
    pages = built()
    out, seen = [], set()

    def add(src, dst):
        if src in seen:
            return
        seen.add(src)
        out.append((src, dst))

    # 1. legacy rules from the old site, flattened
    legacy = []
    for line in (OLD / "_redirects").read_text().split("\n"):
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("https://"):
            continue
        parts = line.split()
        if len(parts) < 2 or parts[0] == "/*.html":
            continue
        if parts[0] in BLOCK:
            continue
        legacy.append((parts[0], resolve(parts[1], pages)))

    # 2. consolidations, in both extensionless and .html form
    cons = []
    for src, dst in CONSOLIDATE.items():
        final = resolve(dst, pages)
        cons.append((src, final))
        cons.append((src + ".html", final))

    lines = [
        "# bcom ICT — Cloudflare Pages redirects.",
        "# GENERATED by build/redirects.py. Edit that, not this file.",
        "#",
        "# Order matters: the .html catch-all at the bottom must stay last.",
        "# The old site's rules for /it-support-{southport,robina,burleigh-heads}",
        "# are deliberately NOT carried across — those are real pages again.",
        "",
        "# --- apex to www -------------------------------------------------------",
        "https://bcomservices.com/*    https://www.bcomservices.com/:splat    301",
        "",
        "# --- consolidated during the rebuild -----------------------------------",
    ]
    for src, dst in sorted(set(cons)):
        add(src, dst)
        lines.append(f"{src:<62} {dst:<52} 301")

    lines += ["", "# --- carried across from the previous site (flattened) ------------------"]
    for src, dst in sorted(set(legacy)):
        if src in seen:
            continue
        add(src, dst)
        lines.append(f"{src:<62} {dst:<52} 301")

    lines += [
        "",
        "# --- strip .html from any remaining URL (must be last) -----------------",
        "/*.html                                                        /:splat"
        "                                              301",
        "",
    ]
    (ROOT / "_redirects").write_text("\n".join(lines))
    print(f"_redirects written — {len(seen)} rules + apex + catch-all")


if __name__ == "__main__":
    main()
